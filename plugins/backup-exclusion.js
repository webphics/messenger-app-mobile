/**
 * What is kept out of a device backup, and the exact text that tells each
 * platform so.
 *
 * The Store is a support history: after #44 every Message of every thread that
 * has been opened, sitting in a plain SQLite file that `expo-sqlite` cannot
 * encrypt. ADR-0008's reasoning for leaving it unencrypted assumes the file
 * stays on the device, and an automatic backup is precisely the thing that
 * assumption does not survive — so the file is excluded from one, on both
 * platforms. See ADR-0011.
 *
 * This half is pure: it builds strings and decides whether a manifest is safe to
 * write to, and imports nothing. `with-store-excluded-from-backup.js` next door
 * owns the filesystem, the manifest and the AppDelegate — the same split as
 * `store-eviction` / `conversation-store` and `attachment-budget` /
 * `attachment-cache`, and for the same reason: a config plugin is otherwise the
 * one part of this repo nothing can be asserted about without a native build.
 */

/**
 * `expo-sqlite` opens every database under a `SQLite` directory — inside
 * `filesDir` on Android, inside `Documents` on iOS. Excluding the directory
 * rather than `joychat-store.db` is deliberate: SQLite writes `-wal` and `-shm`
 * beside the database, and a rule naming only the database would back up the
 * write-ahead log holding the newest Messages.
 */
const STORE_DIRECTORY = "SQLite"

/**
 * Two exclusions, because pointing the manifest at our rules replaces the ones
 * `expo-secure-store` ships — Android takes a single `fullBackupContent` and a
 * single `dataExtractionRules`, so there is no adding to somebody else's.
 * Restating its rule is what keeps the Session cookie out of a backup.
 *
 * These are excludes and nothing else, which is a change of *mode* rather than
 * of one rule: `expo-secure-store`'s files open with
 * `<include domain="sharedpref" path="."/>`, and one `<include>` anywhere turns
 * the whole document into an allow-list — under its rules the app's files and
 * databases were not backed up at all. With no `<include>` the document is a
 * deny-list: everything is backed up except what is named here. That is the
 * point of doing it this way rather than with the app-wide `allowBackup: false`
 * this replaces, and it is what ADR-0011 means by the rest of the app being
 * restored onto a new phone.
 */
const EXCLUSIONS = [
  { domain: "sharedpref", path: "SecureStore" },
  { domain: "file", path: STORE_DIRECTORY },
]

const BACKUP_RULES_FILE = "joychat_backup_rules.xml"
const DATA_EXTRACTION_RULES_FILE = "joychat_data_extraction_rules.xml"

const BACKUP_RULES_RESOURCE = "@xml/joychat_backup_rules"
const DATA_EXTRACTION_RULES_RESOURCE = "@xml/joychat_data_extraction_rules"

const SECURE_STORE_BACKUP_RULES_RESOURCE = "@xml/secure_store_backup_rules"
const SECURE_STORE_DATA_EXTRACTION_RULES_RESOURCE = "@xml/secure_store_data_extraction_rules"

function excludeElements(indent) {
  return EXCLUSIONS.map(
    ({ domain, path }) => `${indent}<exclude domain="${domain}" path="${path}"/>`,
  ).join("\n")
}

/** Android 11 and lower read this one. */
function fullBackupContentXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-store-excluded-from-backup.js. Do not edit. -->
<full-backup-content>
${excludeElements("  ")}
</full-backup-content>
`
}

/**
 * Android 12 and higher read this one, and it has two halves. `device-transfer`
 * is the phone-to-phone copy rather than the cloud, and the Store is excluded
 * from it too: the Session cookie it belongs to cannot travel — the keychain is
 * excluded from both — and a Store that arrives without one is a support history
 * on a device nobody has signed into.
 */
function dataExtractionRulesXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-store-excluded-from-backup.js. Do not edit. -->
<data-extraction-rules>
  <cloud-backup>
${excludeElements("    ")}
  </cloud-backup>
  <device-transfer>
${excludeElements("    ")}
  </device-transfer>
</data-extraction-rules>
`
}

/**
 * What `<application>` should carry, given what it carries now.
 *
 * Three cases are ours to take: nothing set, the rules `expo-secure-store`'s
 * plugin set (whose one exclusion ours restates), and our own from a previous
 * prebuild. Anything else belongs to a plugin added after this one, and
 * replacing it would silently drop whatever it was protecting — so it throws
 * rather than guessing, the way `with-system-bar-insets` does.
 */
function backupAttributes(current) {
  const claim = (attribute, ours, secureStore) => {
    const held = current[attribute]
    if (held && held !== ours && held !== secureStore) {
      throw new Error(
        `with-store-excluded-from-backup: ${attribute} is already set to ${held}. ` +
          `Fold the Store's exclusion into those rules instead, or remove them; ` +
          `Android reads only one ${attribute}.`,
      )
    }
    return ours
  }

  return {
    "android:fullBackupContent": claim(
      "android:fullBackupContent",
      BACKUP_RULES_RESOURCE,
      SECURE_STORE_BACKUP_RULES_RESOURCE,
    ),
    "android:dataExtractionRules": claim(
      "android:dataExtractionRules",
      DATA_EXTRACTION_RULES_RESOURCE,
      SECURE_STORE_DATA_EXTRACTION_RULES_RESOURCE,
    ),
  }
}

/**
 * iOS has no per-file backup rules. The flag is a resource value on the URL,
 * set once and inherited by everything inside a directory — so the directory
 * `expo-sqlite` will open the database in is created here, before anything has
 * opened one, and marked.
 */
const EXCLUSION_FUNCTION = "joychatExcludeStoreFromBackup"

const LAUNCH_ANCHOR =
  "return super.application(application, didFinishLaunchingWithOptions: launchOptions)"

const HELPER = `
// MARK: - Store backup exclusion (plugins/with-store-excluded-from-backup.js)

/**
 The Store must not leave the phone in an iCloud or iTunes backup — see ADR-0011.

 A file-scope function rather than a method on AppDelegate: the class body has no
 anchor a template change would not move, and this needs none.

 Failures are swallowed. A phone that will not take the flag is a phone whose
 Store is backed up, which is not something the person holding it could act on,
 and not a reason to refuse to launch.
 */
private func ${EXCLUSION_FUNCTION}() {
  let manager = FileManager.default
  guard let documents = manager.urls(for: .documentDirectory, in: .userDomainMask).first else {
    return
  }
  var store = documents.appendingPathComponent("${STORE_DIRECTORY}", isDirectory: true)
  do {
    try manager.createDirectory(at: store, withIntermediateDirectories: true)
    var values = URLResourceValues()
    values.isExcludedFromBackup = true
    try store.setResourceValues(values)
  } catch {
    // Deliberately silent; see above.
  }
}
`

function excludeStoreInAppDelegate(source) {
  // Idempotent: prebuild can run repeatedly against an existing ios/.
  if (source.includes(EXCLUSION_FUNCTION)) return source

  if (!source.includes(LAUNCH_ANCHOR)) {
    throw new Error(
      "with-store-excluded-from-backup: could not find `didFinishLaunchingWithOptions` calling " +
        "super in AppDelegate.swift. Run `expo prebuild --clean -p ios` and check the template.",
    )
  }

  // `FileManager` and `URLResourceValues` are Foundation, and nothing the
  // template imports re-exports it. Prepended rather than threaded in after the
  // last import, because Swift takes an import anywhere at file scope.
  const imported = source.includes("import Foundation") ? source : `import Foundation\n${source}`

  return `${imported.replace(LAUNCH_ANCHOR, `${EXCLUSION_FUNCTION}()\n\n    ${LAUNCH_ANCHOR}`)}\n${HELPER}`
}

module.exports = {
  BACKUP_RULES_FILE,
  BACKUP_RULES_RESOURCE,
  DATA_EXTRACTION_RULES_FILE,
  DATA_EXTRACTION_RULES_RESOURCE,
  SECURE_STORE_BACKUP_RULES_RESOURCE,
  SECURE_STORE_DATA_EXTRACTION_RULES_RESOURCE,
  STORE_DIRECTORY,
  backupAttributes,
  dataExtractionRulesXml,
  excludeStoreInAppDelegate,
  fullBackupContentXml,
}
